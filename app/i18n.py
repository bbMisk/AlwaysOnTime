def get_locale():
    """Get current locale from request or default to English."""
    return request.args.get('lang', 'en') or 'en'

def translate(key, locale=None):
    """Translate a key to the given locale."""
    if locale is None:
        locale = get_locale()
    return TRANSLATIONS.get(locale, TRANSLATIONS['en']).get(key, key)

def get_translations(locale=None):
    """Get all translations for a locale."""
    if locale is None:
        locale = get_locale()
    return TRANSLATIONS.get(locale, TRANSLATIONS['en'])

